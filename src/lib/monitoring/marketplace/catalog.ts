const BY_DOMAIN = new Map(MARKETPLACES.map((entry) => [entry.domain, entry]));

export function lookupMarketplace(hostname: string): MarketplaceRecord | null {
  const host = hostname.replace(/^www\./i, "").toLowerCase();
  const exact = BY_DOMAIN.get(host);
  if (exact) return exact;
  let best: MarketplaceRecord | null = null;
  for (const entry of MARKETPLACES) {
    if (host.endsWith(`.${entry.domain}`) && (!best || entry.domain.length > best.domain.length)) {
      best = entry;
    }
  }
  return best;
}

